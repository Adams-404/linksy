describe('firewall - default route parsing', () => {
  it('extracts the device from a default route', () => {
    const output = [
      'default via 192.168.1.1 dev wlp0s20f3 proto dhcp src 192.168.1.50 metric 600',
      '10.0.0.0/8 via 10.1.1.1 dev tun0 proto static metric 50'
    ].join('\n');

    expect(parseDefaultRouteInterface(output)).toBe('wlp0s20f3');
  });

  it('returns the first default route when several exist (VPN + Wi-Fi)', () => {
    const output = [
      'default via 10.8.0.1 dev tun0 proto static',
      'default via 192.168.1.1 dev wlan0 proto dhcp metric 600'
    ].join('\n');

    expect(parseDefaultRouteInterface(output)).toBe('tun0');
  });

  it('returns null for empty or non-route output', () => {
    expect(parseDefaultRouteInterface('')).toBeNull();
    expect(parseDefaultRouteInterface(null)).toBeNull();
    expect(parseDefaultRouteInterface('192.168.1.0/24 dev wlan0 proto kernel')).toBeNull();
  });
});

describe('firewall - DNS discovery', () => {
  it('rejects loopback stubs and link-local addresses', () => {
    expect(isUsableNameserver('127.0.0.53')).toBe(false);
    expect(isUsableNameserver('127.0.0.1')).toBe(false);
    expect(isUsableNameserver('::1')).toBe(false);
    expect(isUsableNameserver('fe80::1')).toBe(false);
    expect(isUsableNameserver('169.254.1.1')).toBe(false);
    expect(isUsableNameserver('0.0.0.0')).toBe(false);
    expect(isUsableNameserver('')).toBe(false);
    expect(isUsableNameserver(null)).toBe(false);
  });

  it('accepts real upstream resolvers', () => {
    expect(isUsableNameserver('1.1.1.1')).toBe(true);
    expect(isUsableNameserver('192.168.1.1')).toBe(true);
    expect(isUsableNameserver('2606:4700:4700::1111')).toBe(true);
  });

  it('parses and de-duplicates nameserver lines', () => {
    const resolv = [
      '# Generated by NetworkManager',
      'nameserver 192.168.1.1',
      'Nameserver 8.8.8.8',
      'nameserver 127.0.0.53',
      'nameserver 192.168.1.1',
      'search lan'
    ].join('\n');

    expect(parseNameservers(resolv)).toEqual(['192.168.1.1', '8.8.8.8']);
    expect(parseNameservers('')).toEqual([]);
    expect(parseNameservers(null)).toEqual([]);
  });

  it('parses NetworkManager per-device DNS output', () => {
    const output = [
      'GENERAL.DEVICE:wlp0s20f3',
      'IP4.DNS[1]:192.168.1.1',
      'IP4.DNS[2]:1.1.1.1',
      'IP6.DNS[1]:2606:4700:4700::1111',
      'IP4.DNS[3]:127.0.0.53'
    ].join('\n');

    expect(parseNmcliDns(output)).toEqual(['192.168.1.1', '1.1.1.1', '2606:4700:4700::1111']);
  });
});

describe('firewall - uplink selection', () => {
  it('uses the Wi-Fi interface when it carries the default route', () => {
    expect(buildUplinkList({ iface: 'wlan0', defaultRouteIface: 'wlan0' })).toEqual(['wlan0']);
  });

  it('adds the default-route device when it differs (VPN / VM / USB modem)', () => {
    expect(buildUplinkList({ iface: 'wlan0', defaultRouteIface: 'tun0' })).toEqual(['wlan0', 'tun0']);
    expect(buildUplinkList({ iface: 'wlan0', defaultRouteIface: 'eth0' })).toEqual(['wlan0', 'eth0']);
  });

  it('never treats the hotspot interface, lo, or the PAN bridge as an uplink', () => {
    expect(buildUplinkList({ iface: 'ap0', defaultRouteIface: 'lo', apIface: 'ap0' })).toEqual([]);
    expect(buildUplinkList({ iface: 'pan0', defaultRouteIface: 'wlan0' })).toEqual(['wlan0']);
  });

  it('tolerates missing input', () => {
    expect(buildUplinkList()).toEqual([]);
    expect(buildUplinkList({ iface: null, defaultRouteIface: undefined })).toEqual([]);
  });
});

describe('firewall - nftables drop-policy detection', () => {
  const kaliStyleRuleset = `table inet filter {
\tchain input {
\t\ttype filter hook input priority filter; policy accept;
\t}
\tchain forward {
\t\ttype filter hook forward priority filter; policy drop;
\t}
}
`;

  it('finds a forward chain with policy drop', () => {
    expect(parseNftForwardDropChains(kaliStyleRuleset)).toEqual([
      { family: 'inet', table: 'filter', chain: 'forward' }
    ]);
  });

  it('does not report accept-policy chains', () => {
    const acceptOnly = `table inet filter {
\tchain forward {
\t\ttype filter hook forward priority filter; policy accept;
\t}
}`;
    expect(parseNftForwardDropChains(acceptOnly)).toEqual([]);
  });

  it('detects input drop chains separately from forward chains', () => {
    const ruleset = `table inet filter {
\tchain input {
\t\ttype filter hook input priority filter; policy drop;
\t}
\tchain forward {
\t\ttype filter hook forward priority filter; policy accept;
\t}
}`;
    expect(parseNftDropChains(ruleset, 'input')).toEqual([
      { family: 'inet', table: 'filter', chain: 'input' }
    ]);
    expect(parseNftForwardDropChains(ruleset)).toEqual([]);
  });

  it('handles single-line chain declarations', () => {
    const ruleset = 'table ip mytable { chain forward { type filter hook forward priority 0; policy drop; } }';
    expect(parseNftForwardDropChains(ruleset)).toEqual([
      { family: 'ip', table: 'mytable', chain: 'forward' }
    ]);
  });

  it('handles firewalld rulesets without a drop policy', () => {
    const ruleset = `table inet firewalld {
\tchain filter_FORWARD {
\t\ttype filter hook forward priority filter + 10; policy accept;
\t}
\tchain filter_INPUT {
\t\ttype filter hook input priority filter + 10; policy accept;
\t}
}`;
    expect(parseNftForwardDropChains(ruleset)).toEqual([]);
  });

  it('returns an empty list for invalid input', () => {
    expect(parseNftForwardDropChains('')).toEqual([]);
    expect(parseNftForwardDropChains(null)).toEqual([]);
  });

  it('the shell helper detects the same drop chains as the JS parser', () => {
    const ruleset = `table inet blockall {
\tchain forward {
\t\ttype filter hook forward priority filter - 10; policy drop;
\t}
\tchain input {
\t\ttype filter hook input priority filter - 10; policy drop;
\t}
\tchain output {
\t\ttype filter hook output priority filter; policy accept;
\t}
}
table inet firewalld {
\tchain filter_FORWARD {
\t\ttype filter hook forward priority filter + 10; policy accept;
\t}
}
`;

    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'linksy-nft-'));
    const fixture = path.join(dir, 'ruleset.txt');
    const stub = path.join(dir, 'nft');
    fs.writeFileSync(fixture, ruleset);
    // Stub nft ignores its arguments and prints the captured ruleset.
    fs.writeFileSync(stub, `#!/bin/sh\ncat "${fixture}"\n`, { mode: 0o755 });

    const run = hook => execFileSync(
      'bash',
      ['-c', `NFT_BIN="${stub}"\n${generateNftDropChainsFunction()}\nnft_drop_chains ${hook}`],
      { encoding: 'utf8' }
    ).trim().split('\n').filter(Boolean);

    expect(run('forward')).toEqual(['inet blockall forward']);
    expect(run('input')).toEqual(['inet blockall input']);
  });
});

describe('firewall - state file', () => {
  it('parses the runtime state written by the start script', () => {
    const state = parseStateFile([
      'AP_IFACE=ap0',
      'UPLINKS=wlan0,eth0',
      'UPLINK=wlan0',
      'NAT_BACKEND=iptables',
      'NAT_OK=1',
      'FIREWALL=ufw',
      'FORWARDING=1',
      'DNS_SERVERS=192.168.1.1 1.1.1.1',
      'DNSMASQ_RUNNING=1',
      'UPDATED_AT=1729500000'
    ].join('\n'));

    expect(state.AP_IFACE).toBe('ap0');
    expect(state.UPLINKS).toBe('wlan0,eth0');
    expect(state.NAT_BACKEND).toBe('iptables');
    expect(state.NAT_OK).toBe('1');
    expect(state.DNS_SERVERS).toBe('192.168.1.1 1.1.1.1');
  });

  it('ignores blank lines and comments and tolerates invalid input', () => {
    expect(parseStateFile('# comment\n\nNAT_OK=0\n')).toEqual({ NAT_OK: '0' });
    expect(parseStateFile('')).toEqual({});
    expect(parseStateFile(null)).toEqual({});
  });
});

describe('firewall - package names per package manager', () => {
  it('maps each supported package manager to an iptables package', () => {
    expect(getFirewallPackageName('apt')).toBe('iptables');
    expect(getFirewallPackageName('dnf')).toBe('iptables-nft');
    expect(getFirewallPackageName('pacman')).toBe('iptables-nft');
    expect(getFirewallPackageName('zypper')).toBe('iptables');
    expect(getFirewallPackageName('unknown')).toBeNull();
    expect(getFirewallPackageName(null)).toBeNull();
  });
});

describe('firewall - shell snippet generation', () => {
  it('sets up NAT without hardcoding a single backend', () => {
    const script = generateFirewallSetupScript();

    expect(script).toContain('for _candidate in iptables iptables-nft; do');
    expect(script).toContain('"$IPT_BIN" -w 5 "$@"');
    expect(script).toContain('add table ip linksy_nat');
    expect(script).toContain('nft_drop_chains forward');
    expect(script).toContain('ufw route allow in on "$AP_IFACE"');
    expect(script).toContain('firewall-cmd --zone=trusted --add-interface="$AP_IFACE"');
    expect(script).toContain('ip -4 route show default');
    expect(script).toContain('NAT_BACKEND="none"');
    expect(script).toContain('if [ "$FORWARDING" != "1" ]; then');
    expect(script).toContain('NAT_OK=0');
  });

  it('uses the caller subnet for nftables NAT (Bluetooth PAN)', () => {
    expect(generateFirewallSetupScript()).toContain('ip saddr 192.168.42.0/24 masquerade');
    expect(generateFirewallSetupScript({ subnet: '10.42.0.0/24' }))
      .toContain('ip saddr 10.42.0.0/24 masquerade');
  });

  it('tears down iptables, ufw and nftables rules', () => {
    const script = generateFirewallTeardownScript();

    expect(script).toContain('ipt_del_all -t nat -D POSTROUTING -o "$_uplink" -j MASQUERADE');
    expect(script).toContain('ufw route delete allow in on "$AP_IFACE"');
    expect(script).toContain('nft delete rule "$_family" "$_table" "$_chain" handle "$_handle"');
    expect(script).toContain('nft delete table ip linksy_nat');
    expect(script).toContain('rm -f "$STATE_FILE"');
  });

  it('discovers upstream DNS and writes a readable resolv file for dnsmasq', () => {
    const script = generateDnsDiscoveryScript();

    expect(script).toContain('/run/NetworkManager/resolv.conf');
    expect(script).toContain('/run/systemd/resolve/resolv.conf');
    expect(script).toContain('/etc/resolv.conf');
    expect(script).toContain('nmcli -t -f IP4.DNS,IP6.DNS device show');
    expect(script).toContain('127.*');
    expect(script).toContain('192.168.42.1|10.42.0.1');
    expect(script).toContain('upstream-dns.conf');
  });

  it('records the runtime state for status and doctor', () => {
    const script = generateStateWriteScript();

    expect(script).toContain('echo "NAT_BACKEND=$NAT_BACKEND"');
    expect(script).toContain('echo "NAT_OK=$NAT_OK"');
    expect(script).toContain('echo "DNS_SERVERS=$DNS_SERVERS"');
  });
});
